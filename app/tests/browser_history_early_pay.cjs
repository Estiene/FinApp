const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const assert=(value,message)=>{if(!value) throw Error(message);};
  await page.goto('http://127.0.0.1:5088/balance-history');
  assert((await page.locator('body').innerText()).includes('No saved forecasts'),'missing-history explanation');
  await page.getByRole('button',{name:'Save forecast',exact:true}).click();
  await page.waitForLoadState('load');
  assert(await page.locator('svg[role="img"]').count()===1,'saved forecast chart');
  const firstForecast = await page.locator('details').filter({hasText:'Saved forecast #1'}).locator('table').textContent();
  await page.goto('http://127.0.0.1:5088/accounts');
  await page.locator('select[name="early_pay_days"]').first().selectOption('2');
  await page.locator('select[name="early_pay_days"]').first().locator('..').getByRole('button',{name:'Save',exact:true}).click();
  await page.waitForLoadState('load');
  assert(await page.locator('select[name="early_pay_days"]').first().inputValue()==='2','per-account early pay save');
  await page.goto('http://127.0.0.1:5088/report?year=2026&month=12');
  await page.locator('.cash-section').first().evaluate(element=>element.open=true);
  assert((await page.locator('.cash-day').filter({hasText:'12/30'}).innerText()).includes('200.00'),'cross-year early deposit');
  await page.goto('http://127.0.0.1:5088/');
  await page.getByRole('button',{name:'Bank Accounts',exact:true}).click();
  await page.locator('[name="starting_balance"]').first().fill('123.45');
  await page.locator('[name="starting_balance"]').first().locator('xpath=ancestor::form').getByRole('button',{name:'Save',exact:true}).click();
  await page.waitForLoadState('load');
  await page.goto('http://127.0.0.1:5088/balance-history');
  assert(await page.locator('details').filter({hasText:'Saved forecast #1'}).locator('table').textContent()===firstForecast,'historical forecast stable after balance/early pay changes');
  await page.locator('details').filter({hasText:'Actual balance observations'}).locator('summary').click();
  assert((await page.locator('body').innerText()).includes('$123.45'),'actual observation recorded');
  await page.getByRole('button',{name:'Save forecast',exact:true}).click();
  await page.waitForLoadState('load');
  assert(await page.locator('polyline').count()===2,'compare multiple forecasts');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile history layout');
  assert(errors.length===0,'browser errors '+errors.join('; '));
  console.log('History/Early Pay browser checks passed.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
