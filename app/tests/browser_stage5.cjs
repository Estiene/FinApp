const { chromium } = require('playwright');
(async()=>{
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const context=await browser.newContext(); const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const assert=(x,msg)=>{if(!x)throw Error(msg)};
await page.goto('http://127.0.0.1:5088/');
assert(await page.locator('#dashboard-bank').isVisible(),'bank default');
await page.getByRole('button',{name:'Credit Cards',exact:true}).click();
assert(await page.locator('#dashboard-card').isVisible(),'card selector');
assert((await page.locator('#dashboard-card').innerText()).includes('$3,500.00'),'credit limit');
assert((await page.locator('#dashboard-card').innerText()).includes('Inactive'),'inactive label');
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile dashboard overflow');
await page.goto('http://127.0.0.1:5088/report?year=2026&month=11');
await page.locator('[name="starting_balance_1"]').fill('250');
await Promise.all([page.waitForURL(/starting_balance_1=250/),page.getByRole('button',{name:'Apply',exact:true}).click()]);
await page.goto('http://127.0.0.1:5088/');
assert(await page.locator('#dashboard-card').isVisible(),'retained view');
await page.goto('http://127.0.0.1:5088/report?year=2026&month=11');
await page.waitForURL(/starting_balance_1=250/);
assert(await page.locator('[name="starting_balance_1"]').inputValue()==='250.00','retained balances applied');
await page.locator('#cash-search').fill('INTERNET');
assert(await page.locator('.cash-day:visible').count()===1,'name search');
assert((await page.locator('.cash-day:visible').innerText()).includes('220.00'),'full balance preserved');
await page.locator('#cash-search').fill('$30.00');
assert(await page.locator('.cash-day:visible').count()===1,'amount search');
await page.locator('#cash-search').fill('nonexistent');
assert((await page.locator('#search-status').innerText()).includes('0 matching'),'no matches');
await page.locator('#clear-search').click();
assert(await page.locator('.cash-section').isVisible(),'clear search');
await page.locator('#reset-simulation').click();
await page.waitForURL(u=>!u.searchParams.has('starting_balance_1'));
assert(await page.locator('[name="starting_balance_1"]').inputValue()==='0.00','reset');
assert(errors.length===0,'js errors '+errors.join());
console.log('Browser QA passed: selector, mobile dashboard, limit/status, session restoration, name/amount search, unchanged balances, clear/reset.');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
